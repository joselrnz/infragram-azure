#!/usr/bin/env python3
"""Generate the node class tree from the icon catalogs and the shared library.

Writes ``src/infragram/nodes/<collection>/<category>.py``, one module per
vendor category, each holding an inheritance chain::

    Element                     models/topology.py -- the pydantic node
      └─ _Azure                 collection base, carries COLLECTION
           └─ _Compute          category base, carries CATEGORY
                └─ VirtualMachine   leaf, carries ICON and TYPE

so a build script writes ``azure.compute.VirtualMachine("Web tier")`` and the
artwork follows from the class, not from a path spelled out by hand.

Two more packages come from the catalog module rather than from icon files:

- ``nodes/infragram/<category>.py`` - the shared primitives every library
  offers (clients, users, mainframe, SAN switch, brand marks ...);
- ``nodes/frames/<group>.py`` - the containment frames of every gallery
  (``frames.aws.VPC``, ``frames.onprem.Subnet``, ``frames.generic.DMZ``),
  each carrying its frame id, kind and gallery group.

Generated at maintenance time and committed, rather than conjured at import:
the files are greppable, the classes are real, and an editor can complete
them. Rerun after importing new icons or adding primitives or frames.

Beside each module sits a type stub (``<category>.pyi``) that gives every
class the ``__init__`` its base really has. A type checker builds each
pydantic class an ``__init__`` of its model fields unless the class declares
one itself -- a base's does not count -- so without the stub
``compute.VirtualMachine("Web tier")`` reads as an error and an editor offers
``id=``, ``name=``, ``type=``. The signature is read from ``Element`` and
``Frame`` as they stand, so ``--check`` fails when either changes.

    python scripts/tools/generate-nodes.py
    python scripts/tools/generate-nodes.py --check    # CI drift gate
"""

