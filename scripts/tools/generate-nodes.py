def module_name(category: str) -> str:
    """``ai-machine-learning`` -> ``ai_machine_learning``."""
    cleaned = "".join(ch if ch.isalnum() else "_" for ch in category.lower())
    cleaned = "_".join(part for part in cleaned.split("_") if part) or "general"
    return cleaned if not cleaned[0].isdigit() else "c" + cleaned


def collections() -> dict[str, Path]:
    """Every catalog we ship, keyed by collection name."""
    found: dict[str, Path] = {}
    for root in (ICONS / "vendors", ICONS):
        if not root.is_dir():
            continue
        for entry in sorted(root.iterdir()):
            if (entry / "catalog.json").is_file() and entry.name not in found:
                found[entry.name] = entry
    return found


def category_of(icon: dict) -> str:
    single = icon.get("category")
    if single:
        return str(single)
    many = icon.get("categories") or []
    return str(many[0]) if many else "general"


def _dedupe(entries: list[dict]) -> None:
    """Sort by class and number repeats: two ``Bastion`` become Bastion, Bastion2."""
    entries.sort(key=lambda e: e["class"])
    seen: dict[str, int] = {}
    for entry in entries:
        count = seen.get(entry["class"], 0)
        seen[entry["class"]] = count + 1
        if count:
            entry["class"] = f"{entry['class']}{count + 1}"


def group(path: Path) -> dict[str, list[dict]]:
    """Catalog entries bucketed by category, each with its class name."""
    catalog = json.loads((path / "catalog.json").read_text(encoding="utf-8"))
    buckets: dict[str, list[dict]] = {}
    # Service name -> class, so a resource glyph can name the service it
    # belongs to and nobody reaches for the wrong one of a look-alike pair.
    services = tiers.service_names(catalog["icons"])
    by_name = {
        name: str(icon.get("class_name") or class_name(str(icon.get("id") or "")))
        for name, icon in services.items()
    }
    for icon in catalog["icons"]:
        slug = str(icon.get("id") or "")
        name = str(icon.get("class_name") or class_name(slug))
        if not name:
            continue
        brand = str(icon.get("brand_hex") or "").strip().lstrip("#")
        entry = {
            "class": name,
            "icon": slug,
            "type": str(icon.get("name") or slug),
            # A resource glyph is the drawing the vendor places inside a
            # service's group box. Naming the service on the class is what
            # stops someone reaching for the resource when they mean the
            # service -- the two read alike in a list.
            "tier": tiers.CONTAINER_TIER
            if tiers.is_container(icon)
            else ("resource" if tiers.is_resource(icon) else "service"),
            "parent": by_name.get((tiers.parent_service(icon, services) or {}).get("name", ""), ""),
            # Group artwork is the box drawn around things. Its class name
            # collides with the frame that does the same job, so the class
            # says which frame to reach for instead.
            "instead": (
                tiers.container_advice(path.name, slug) if tiers.is_container(icon) else ""
            ),
            # A service icon that names something a frame also does. Real to
            # place, but it holds nothing, so the class points at the frame
            # for when containment is what was meant.
            "counterpart": tiers.counterpart_advice(path.name, slug),
            # Brand colour travels with the class, so a logo node can be
            # tinted without the build script knowing the hex.
            "brand": f"#{brand.lower()}" if len(brand) in (3, 6) else "",
        }
        categories = (category_of(icon), *map(str, icon.get("compat_categories") or ()))
        compat_class_names = icon.get("compat_class_names") or {}
        for category in dict.fromkeys(categories):
            category_entry = dict(entry)
            if isinstance(compat_class_names, dict) and category in compat_class_names:
                category_entry["class"] = str(compat_class_names[category])
            buckets.setdefault(category, []).append(category_entry)
    for entries in buckets.values():
        _dedupe(entries)
    return dict(sorted(buckets.items()))


#: Libraries whose components are Python specs rather than an icon pack, or
#: beside one. They still deserve node classes, so a build script names the
#: service the same way it names an AWS one. A library with both (Cloudflare:
#: four product marks beside the drawn tiles) gets one package holding both;
#: a tile that took a mark's id keeps the class, the mark is skipped.
SPEC_LIBRARIES = {
    "infragram": SHARED_PRIMITIVE_SPECS,
    "cloudflare": CLOUDFLARE_COMPONENT_SPECS,
}


def spec_buckets(specs, taken: set[str] | None = None) -> dict[str, list[dict]]:
    """Component specs bucketed by canonical category.

    ``taken`` is the icon ids a pack already turned into classes; a spec with
    one of those ids is a duplicate and stays out.
    """
    buckets: dict[str, list[dict]] = {}
    for spec in specs:
        name = class_name(spec.service_id)
        if not name or spec.service_id in (taken or ()):
            continue
        buckets.setdefault(spec.category_id, []).append(
            {
                "class": name,
                "icon": spec.service_id,
                "type": spec.name,
                "brand": "",
            }
        )
    for entries in buckets.values():
        _dedupe(entries)
    return dict(sorted(buckets.items()))


def merged_buckets(path: Path, specs) -> dict[str, list[dict]]:
    """A pack's buckets with a spec library's classes beside them.

    Category by category, so ``security.WAF`` (a tile) and ``compute.Workers``
    (a mark) come out of the same package; the classes of each category are
    numbered again afterwards in case a mark and a tile share a name.
    """
    buckets = group(path)
    taken = {entry["icon"] for entries in buckets.values() for entry in entries}
    for category, entries in spec_buckets(specs, taken).items():
        buckets.setdefault(category, []).extend(entries)
    for entries in buckets.values():
        _dedupe(entries)
    return dict(sorted(buckets.items()))


def frame_class_slug(frame_id: str, group_id: str) -> str:
    """``custom-boundary-aws-public-subnet`` in group aws -> ``public-subnet``."""
    slug = frame_id.removeprefix("custom-boundary-")
    token = FRAME_GROUP_TOKENS.get(group_id, "")
    if token and slug.startswith(token) and len(slug) > len(token):
        slug = slug[len(token) :]
    return slug.removesuffix("-generic")


def frame_buckets() -> dict[str, tuple[str, list[dict]]]:
    """Frame group -> (display label, frame entries), gallery order."""
    labels = dict(ARCHITECTURE_BOUNDARY_GROUPS)
    buckets: dict[str, list[dict]] = {}
    for frame_id, label, subtitle, kind, _glyph, _paint in ARCHITECTURE_BOUNDARY_SPECS:
        group_id = architecture_boundary_group(frame_id)
        name = class_name(frame_class_slug(frame_id, group_id))
        if not name:
            continue
        buckets.setdefault(group_id, []).append(
            {
                "class": name,
                "frame_id": frame_id,
                "kind": kind,
                "label": label,
                "subtitle": subtitle,
            }
        )
    for entries in buckets.values():
        _dedupe(entries)
    ordered = {
        group_id: (labels.get(group_id, group_id), buckets[group_id])
        for group_id, _ in ARCHITECTURE_BOUNDARY_GROUPS
        if group_id in buckets
    }
    for group_id in sorted(set(buckets) - set(ordered)):
        ordered[group_id] = (labels.get(group_id, group_id), buckets[group_id])
    return ordered


def _docstring(entry: dict) -> str:
    """The class docstring, which says what the glyph is for.

    Two kinds of artwork are easy to reach for by mistake, and both are
    caught here, where a caller actually meets the choice. A resource
    glyph is what the vendor draws inside a service's group box, and its
    class sits beside the service's -- RDSMultiAz next to RDS. Group
    artwork is the box itself, and its class name collides with the frame
    that does the same job -- Region next to frames.aws.Region.
    """
    quote = chr(34) * 3
    if entry.get("tier") == tiers.CONTAINER_TIER and entry.get("instead"):
        return (
            f"    {quote}{entry['type']}."
            + chr(10)
            + chr(10)
            + "    Group artwork: the box the vendor draws around things, not a"
            + chr(10)
            + "    node to place beside them. Placed as a node it draws a card"
            + chr(10)
            + "    that contains nothing."
            + chr(10)
            + chr(10)
            + textwrap.fill(
                entry["instead"], width=72, initial_indent="    ", subsequent_indent="    "
            )
            + chr(10)
            + f"    {quote}"
            + chr(10)
        )
    if entry.get("counterpart"):
        return (
            f"    {quote}{entry['type']}."
            + chr(10)
            + chr(10)
            + textwrap.fill(
                entry["counterpart"], width=72, initial_indent="    ", subsequent_indent="    "
            )
            + chr(10)
            + f"    {quote}"
            + chr(10)
        )
    if entry.get("tier") == "resource" and entry.get("parent"):
        return (
            f"    {quote}{entry['type']}."
            + chr(10)
            + chr(10)
            + f"    Resource glyph: what the vendor draws inside a {entry['parent']} group,"
            + chr(10)
            + f"    not the service itself. For the service use ``{entry['parent']}``."
            + chr(10)
            + f"    {quote}"
            + chr(10)
        )
    return f"    {quote}{entry['type']}.{quote}" + chr(10)


def render_category(collection: str, category: str, entries: list[dict]) -> str:
    base = class_name(collection) or collection.title()
    holder = "_" + (class_name(category) or module_name(category).title())
    lines = [
        BANNER,
        f'"""{category.replace("-", " ")} nodes for {collection}."""\n',
        "\nfrom __future__ import annotations\n",
        f"\nfrom . import _{base}\n",
        f"\n\nclass {holder}(_{base}):\n",
        f'    """Base for the {collection} {category.replace("-", " ")} category."""\n',
        "\n",
        f'    CATEGORY = "{category}"\n',
    ]
    for entry in entries:
        lines += [
            f"\n\nclass {entry['class']}({holder}):\n",
            _docstring(entry),
            "\n",
            f'    ICON = "{entry["icon"]}"\n',
            f'    TYPE = "{entry["type"]}"\n',
        ]
        if entry["brand"]:
            lines.append(f'    BRAND = "{entry["brand"]}"\n')
    names = ", ".join(f'"{e["class"]}"' for e in entries)
    lines.append(f"\n\n__all__ = [{names}]\n")
    return "".join(lines)


def render_package(collection: str, buckets: dict[str, list[dict]]) -> str:
    base = class_name(collection) or collection.title()
    modules = sorted(module_name(c) for c in buckets)
    total = sum(len(v) for v in buckets.values())
    listing = "\n".join(f"    {m}" for m in modules)
    quoted = ",\n".join(f'    "{m}"' for m in modules)
    return f'''{BANNER}"""{collection} nodes, in the vendor's own categories.

{total} classes across {len(modules)} categories::

{listing}

Import a category and use its classes::

    from infragram.nodes.{collection} import {modules[0]}

    {modules[0]}.{buckets[sorted(buckets)[0]][0]["class"]}("label", "detail")

Attribute access on this package also finds a class in any category, so
``{collection}.{buckets[sorted(buckets)[0]][0]["class"]}`` works when the category is not worth naming.
"""

from __future__ import annotations

import difflib
import importlib

from .._base import Element

CATEGORIES = (
{quoted},
)

__all__ = ["Element", "_{base}", "CATEGORIES", *CATEGORIES]


class _{base}(Element):
    """Base for every {collection} node class."""

    COLLECTION = "{collection}"


def __getattr__(name: str):
    """A category module, or any class in one of them."""
    if name.startswith("_"):
        raise AttributeError(name)
    if name in CATEGORIES:
        return importlib.import_module(f".{{name}}", __name__)
    known: list[str] = []
    for category in CATEGORIES:
        module = importlib.import_module(f".{{category}}", __name__)
        found = getattr(module, name, None)
        if found is not None:
            return found
        known.extend(getattr(module, "__all__", ()))
    near = difflib.get_close_matches(name, known, n=5, cutoff=0.5)
    hint = f" Did you mean: {{', '.join(near)}}?" if near else ""
    raise AttributeError(
        f"{collection} has no node class {{name!r}} ({{len(known)}} available "
        f"in {{len(CATEGORIES)}} categories).{{hint}}"
    )


def __dir__() -> list[str]:
    return sorted(__all__)
'''


def render_stub(collection: str, buckets: dict[str, list[dict]]) -> str:
    """The package's type stub: every class ``<collection>.<Name>`` finds.

    The package resolves a short name such as ``aws.EC2`` through its
    module ``__getattr__``, which an editor cannot see into, so without the
    stub nothing completes and a type checker flags every short name. The
    stub names what ``__getattr__`` returns, category by category in the
    same order, so a name two categories share resolves to the same class.
    """
    base = class_name(collection) or collection.title()
    by_module = {module_name(category): entries for category, entries in buckets.items()}
    modules = sorted(by_module)
    seen: set[str] = set()
    lines = [
        BANNER,
        f'"""Type stub for ``infragram.nodes.{collection}``: its categories and every\n'
        f'class ``{collection}.<Name>`` finds in them, for editors and type checkers.\n"""\n',
        "\nfrom typing import ClassVar\n",
        "\nfrom .._base import Element as Element\n",
        "from . import (\n" + "".join(f"    {m} as {m},\n" for m in modules) + ")\n",
    ]
    for module in modules:
        names = [e["class"] for e in by_module[module] if e["class"] not in seen]
        seen.update(names)
        # isort's order (ruff's I rules): constants, then classes, each case-blind
        names.sort(
            key=lambda n: (
                0 if n.isupper() and len(n) > 1 else 1 if n[:1].isupper() else 2,
                n.casefold(),
            )
        )
        if names:
            lines.append(
                f"from .{module} import (\n" + "".join(f"    {n} as {n},\n" for n in names) + ")\n"
            )
    lines += [
        "\nCATEGORIES: tuple[str, ...]\n",
        f"\n\nclass _{base}(Element):\n",
        "    COLLECTION: ClassVar[str]\n",
    ]
    return "".join(lines)


def stub_init(base: type) -> str:
    """``base``'s own ``__init__`` as a stub writes it: its parameters and
    their annotations, every default as ``...``."""
    parts: list[str] = []
    keyword_only = False
    # the class's own function: a base's would not be the one that runs, and
    # pydantic gives the class itself a signature of its model fields
    for parameter in inspect.signature(vars(base)["__init__"]).parameters.values():
        if parameter.name == "self":
            parts.append("self")
            continue
        stars = ""
        if parameter.kind is parameter.VAR_POSITIONAL:
            stars = "*"
            keyword_only = True  # what follows *args is keyword-only already
        elif parameter.kind is parameter.VAR_KEYWORD:
            stars = "**"
        elif parameter.kind is parameter.KEYWORD_ONLY and not keyword_only:
            parts.append("*")
            keyword_only = True
        text = f"{stars}{parameter.name}: {parameter.annotation}"
        parts.append(text if parameter.default is parameter.empty else f"{text} = ...")
    return f"    def __init__({', '.join(parts)}) -> None: ...\n"


def render_module_stub(
    module: str, base_import: str, holder: str, base: str, root: type, entries: list[dict]
) -> str:
    """A generated module's type stub: its classes, each with its base's
    ``__init__`` declared on it (the module docstring says why)."""
    init = stub_init(root)
    lines = [
        BANNER,
        f'"""Type stub for ``infragram.nodes.{module}``: each class takes what\n'
        f'``{root.__name__}`` takes, declared on the class so a type checker reads it.\n"""\n',
        "\nfrom typing import Any\n",
        f"\n{base_import}\n",
        "\n__all__: list[str]\n",
        f"\nclass {holder}({base}): ...\n",
    ]
    for entry in entries:
        lines += [f"\nclass {entry['class']}({holder}):\n", init]
    return "".join(lines)


def render_category_stub(collection: str, category: str, entries: list[dict]) -> str:
    base = class_name(collection) or collection.title()
    holder = "_" + (class_name(category) or module_name(category).title())
    return render_module_stub(
        f"{collection}.{module_name(category)}",
        f"from . import _{base}",
        holder,
        f"_{base}",
        Element,
        entries,
    )


def render_frames_stub(group_id: str, entries: list[dict]) -> str:
    base = "_" + (class_name(group_id) or group_id.title())
    return render_module_stub(
        f"frames.{group_id}", "from .._base import Frame", base, "Frame", Frame, entries
    )


def render_frames_module(group_id: str, label: str, entries: list[dict]) -> str:
    base = "_" + (class_name(group_id) or group_id.title())
    listing = "\n".join(f"    {e['class']:<28} {e['kind']:<18} {e['label']}" for e in entries)
    lines = [
        BANNER,
        f'"""{label} frames.\n\n{len(entries)} frames, by class, kind and gallery name::\n\n'
        f'{listing}\n"""\n',
        "\nfrom __future__ import annotations\n",
        "\nfrom .._base import Frame\n",
        f"\n\nclass {base}(Frame):\n",
        f'    """Base for every {label} frame."""\n',
        "\n",
        f'    GROUP = "{group_id}"\n',
    ]
    for entry in entries:
        lines += [
            f"\n\nclass {entry['class']}({base}):\n",
            f'    """{entry["label"]} - {entry["subtitle"]}."""\n',
            "\n",
            f'    FRAME_ID = "{entry["frame_id"]}"\n',
            f'    KIND = "{entry["kind"]}"\n',
            f'    LABEL = "{entry["label"]}"\n',
        ]
    names = ", ".join(f'"{e["class"]}"' for e in entries)
    lines.append(f"\n\n__all__ = [{names}]\n")
    return "".join(lines)


def render_frames_package(groups: dict[str, tuple[str, list[dict]]]) -> str:
    total = sum(len(entries) for _, entries in groups.values())
    listing = "\n".join(f"    {group_id:<14} {label}" for group_id, (label, _) in groups.items())
    quoted = ",\n".join(f'    "{group_id}"' for group_id in groups)
    first_group = next(iter(groups))
    first_class = groups[first_group][1][0]["class"]
    head = (
        f'{BANNER}"""Containment frames as classes, one module per frame gallery.\n\n'
        f"{total} frames across {len(groups)} groups::\n\n{listing}\n\n"
        "A frame is a provider-aware containment boundary. Give it children with\n"
        "``>>`` and it draws around them; leave it empty and it keeps its default\n"
        "size::\n\n"
        f"    from infragram.nodes.frames import {first_group}\n\n"
        f'    {first_group}.{first_class}("label")\n\n'
        "The class carries the frame id and gallery group the editor needs, so the\n"
        'exported document round-trips with the same tab, glyph and colour.\n"""\n'
    )
    body = (
        "\nfrom __future__ import annotations\n"
        "\nimport importlib\n"
        "\nfrom .._base import Frame\n"
        f"\nGROUPS = (\n{quoted},\n)\n"
        '\n__all__ = ["Frame", "GROUPS", *GROUPS]\n'
        "\n\ndef __getattr__(name: str):\n"
        "    if name in GROUPS:\n"
        '        return importlib.import_module(f".{name}", __name__)\n'
        "    raise AttributeError(f\"no frame group {name!r}; groups: {', '.join(GROUPS)}\")\n"
        "\n\ndef __dir__() -> list[str]:\n"
        "    return sorted(__all__)\n"
    )
    return head + body


def plan() -> dict[Path, str]:
    """Every generated file and its content."""
    planned: dict[Path, str] = {}
    packs = collections()
    for collection, path in packs.items():
        buckets = (
            merged_buckets(path, SPEC_LIBRARIES[collection])
            if collection in SPEC_LIBRARIES
            else group(path)
        )
        if not buckets:
            continue
        package = OUT / collection
        planned[package / "__init__.py"] = render_package(collection, buckets)
        planned[package / "__init__.pyi"] = render_stub(collection, buckets)
        for category, entries in buckets.items():
            planned[package / f"{module_name(category)}.py"] = render_category(
                collection, category, entries
            )
            planned[package / f"{module_name(category)}.pyi"] = render_category_stub(
                collection, category, entries
            )

    for collection, specs in SPEC_LIBRARIES.items():
        if collection in packs:
            continue  # merged into the pack's package above
        buckets = spec_buckets(specs)
        if not buckets:
            continue
        package = OUT / collection
        planned[package / "__init__.py"] = render_package(collection, buckets)
        planned[package / "__init__.pyi"] = render_stub(collection, buckets)
        for category, entries in buckets.items():
            planned[package / f"{module_name(category)}.py"] = render_category(
                collection, category, entries
            )
            planned[package / f"{module_name(category)}.pyi"] = render_category_stub(
                collection, category, entries
            )

    frames = frame_buckets()
    package = OUT / "frames"
    planned[package / "__init__.py"] = render_frames_package(frames)
    for group_id, (label, entries) in frames.items():
        planned[package / f"{group_id}.py"] = render_frames_module(group_id, label, entries)
        planned[package / f"{group_id}.pyi"] = render_frames_stub(group_id, entries)
    return planned


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="report drift and exit 1 instead of writing"
    )
    args = parser.parse_args()

    planned = plan()

    if args.check:
        drift = [
            p
            for p, text in planned.items()
            if not p.is_file() or p.read_text(encoding="utf-8") != text
        ]
        stale = [
            p
            for p in (*OUT.rglob("*.py"), *OUT.rglob("*.pyi"))
            if p not in planned and p.name != "_base.py" and p.parent != OUT
        ]
        if drift or stale:
            print(f"FAIL node classes: {len(drift)} out of date, {len(stale)} stale")
            for p in (drift + stale)[:10]:
                print(f"  - {p.relative_to(REPO)}")
            print("  run: python scripts/tools/generate-nodes.py")
            return 1
        print(f"OK node classes: {len(planned)} generated modules match the catalogs")
        return 0

    for package in {p.parent for p in planned}:
        package.mkdir(parents=True, exist_ok=True)
    for path, text in planned.items():
        write_generated_text(path, text)
    for path in (*OUT.rglob("*.py"), *OUT.rglob("*.pyi")):
        if path not in planned and path.name != "_base.py" and path.parent != OUT:
            path.unlink()
    classes = sum(
        text.count("\nclass ") - 1
        for p, text in planned.items()
        if p.suffix == ".py" and p.name != "__init__.py"
    )
    print(f"wrote {len(planned)} modules, {classes} node classes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
